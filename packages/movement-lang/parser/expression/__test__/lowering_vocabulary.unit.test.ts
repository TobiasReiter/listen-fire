// The Rust lowering (crates/movement-parser/src/lowering) refuses calls by
// the same vocabulary the TypeScript declares — the stdlib families, the
// FILE/READ contracts, the options maps, the AI tiers — compiled into the
// WASM from a generated copy (lowering/vocabulary/data.rs). This pins the
// copy to the declarations, so a new stdlib function or option cannot reach
// the checker without reaching the lowering too.
//
// Set UPDATE_LOWERING_VOCABULARY=1 to rewrite the copy (then rebuild the
// WASM: scripts/build-parser-wasm.sh).
import { AI_TIERS } from '@listen-fire/shared/expression/types';
import {
  BUILTIN_OPTIONS,
  FILE_ARTIFACT_TYPES,
  FILE_FUNCTION_ID,
  FILE_SIGNATURE,
  READ_FUNCTION_ID,
  READ_SIGNATURE,
  STDLIB_FAMILIES,
} from '../../../expression/stdlib';

declare function require(id: string): unknown;
declare const process: { env: Record<string, string | undefined> };
declare const __dirname: string;

const DATA_PATH = `${__dirname}/../../../../../crates/movement-parser/src/lowering/vocabulary/data.rs`;

const str = (s: string): string =>
  `"${s
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/[\u0000-\u001f]/g, c => `\\u{${c.charCodeAt(0).toString(16)}}`)}"`;
const strs = (xs: ReadonlyArray<string>): string => `&[${xs.map(str).join(', ')}]`;
const opt = <T>(x: T | undefined, render: (x: T) => string): string => (x === undefined ? 'None' : `Some(${render(x)})`);
const OPTION_TYPES = { number: 'Number', text: 'Text', literal: 'Literal' } as const;

/** The Rust the lowering compiles in (crates/movement-parser/src/lowering/vocabulary.rs types it). */
function vocabularyRust(): string {
  const options = BUILTIN_OPTIONS.map(
    spec => `        OptionsContract {
            fn_: ${str(spec.fn)},
            signature: ${str(spec.signature)},
            arity: ${spec.arity},
            index: ${spec.index},
            options: &[
${spec.options
  .map(
    o => `                OptionSpec {
                    key: ${str(o.key)},
                    type_: OptionType::${OPTION_TYPES[o.type]},
                    required: ${o.required},
                    summary: ${str(o.summary)},
                    values: ${opt(o.values, strs)},
                    unavailable: ${opt(o.unavailable, u => `&[${Object.entries(u).map(([k, v]) => `(${str(k)}, ${str(v)})`).join(', ')}]`)},
                },
`,
  )
  .join('')}            ],
            exactly_one: &[${(spec.exactlyOne ?? []).map(c => `ExactlyOne { keys: ${strs(c.keys)}, what: ${str(c.what)} }`).join(', ')}],
            // The cross-option rule is code; this names the one call_shape::agree carries.
            agree: ${spec.agree === undefined ? 'None' : `Some(${str(spec.fn)})`},
        },
`,
  ).join('');
  const families = STDLIB_FAMILIES.map(
    family => `        Family {
            namespace: ${str(family.namespace)},
            functions: &[
${family.functions
  .map(
    fn => `                FamilyFunction { name: ${str(fn.name)}, id: ${str(fn.id)}, signature: ${str(fn.signature)}, arity: Arity { min: ${fn.arity.min}, max: ${fn.arity.max} } },
`,
  )
  .join('')}            ],
        },
`,
  ).join('');
  return `// Generated by packages/movement-lang/parser/expression/__test__/lowering_vocabulary.unit.test.ts
// from expression/stdlib.ts and shared/expression/types.ts. Do not edit: run it
// with UPDATE_LOWERING_VOCABULARY=1, then rebuild the WASM.

use super::{Arity, ExactlyOne, Family, FamilyFunction, FileContract, OptionSpec, OptionType, OptionsContract, ReadContract, Vocabulary};

pub static VOCABULARY: Vocabulary = Vocabulary {
    ai_tiers: ${strs(AI_TIERS)},
    file: FileContract { fn_: ${str(FILE_FUNCTION_ID)}, signature: ${str(FILE_SIGNATURE)}, artifact_types: ${strs(FILE_ARTIFACT_TYPES)} },
    read: ReadContract { fn_: ${str(READ_FUNCTION_ID)}, signature: ${str(READ_SIGNATURE)} },
    options: &[
${options}    ],
    families: &[
${families}    ],
};
`;
}

describe('the lowering vocabulary', () => {
  const fs = require('fs') as { readFileSync(path: string, encoding: 'utf8'): string; writeFileSync(path: string, data: string): void };
  if (process.env.UPDATE_LOWERING_VOCABULARY) fs.writeFileSync(DATA_PATH, vocabularyRust());

  it('the Rust copy is the TypeScript declarations', () => {
    expect(fs.readFileSync(DATA_PATH, 'utf8')).toBe(vocabularyRust());
  });
});
